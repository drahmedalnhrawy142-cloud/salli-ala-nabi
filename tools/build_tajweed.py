import json, re
q = json.load(open('public/quran/hafs.json', encoding='utf-8'))
def norm(s):
    s = re.sub('[ؐ-ًؚ-ٰٟۖ-ۭـ]', '', s)
    s = re.sub('[أإآٱ]', 'ا', s).replace('ى', 'ي').replace('ة', 'ه').replace('\xa0', '').replace('۞', '').replace('۩', '')
    return s.replace('ء', '').replace('ئ', 'ي').replace('ؤ', 'و')
idx = {(a[0], a[1]): i for i, a in enumerate(q['ayas'])}
def find(s, a, phrase):
    i = idx[(s, a)]; ws = q['ayas'][i][4].split(' '); nw = [norm(w) for w in ws]; p = phrase.split()
    for k in range(len(nw) - len(p) + 1):
        if all(nw[k + j] == norm(p[j]) for j in range(len(p))):
            return [s, a, k, k + len(p)]
    raise SystemExit('not found %s' % [s, a, phrase])
def ex(s, a, p, note=''):
    r = find(s, a, p)
    return {'s': r[0], 's_': 0, 'a': r[1], 'f': r[2], 't': r[3], 'n': note}
